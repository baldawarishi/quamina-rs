//! Generate `src/unicode_category_tables.rs` from the Unicode Character
//! Database.
//!
//! ```text
//! curl -sL https://www.unicode.org/Public/17.0.0/ucd/UnicodeData.txt \
//!     | cargo run --example gen_unicode_categories -- 17.0.0 src/unicode_category_tables.rs
//! ```
//!
//! As in Go's `code_gen/build_unicode_tables.go`, every code point that
//! `UnicodeData.txt` doesn't list is `Cn`, and a `<..., First>`/`<..., Last>`
//! pair covers the range between them. Surrogates (`Cs`) can't appear in a
//! Rust `char` or in valid UTF-8, so they are left out, of `C` as well.

use std::collections::BTreeMap;
use std::fmt::Write;
use std::io::Read;

fn main() {
    let mut args = std::env::args().skip(1);
    let version = args.next().expect("Unicode version");
    let out = args.next().expect("output path");
    let mut data = String::new();
    std::io::stdin().read_to_string(&mut data).unwrap();

    let mut categories = vec!["Cn"; 0x11_0000];
    let mut lines = data.lines();
    while let Some(line) = lines.next() {
        let fields: Vec<&str> = line.split(';').collect();
        let first = usize::from_str_radix(fields[0], 16).unwrap();
        let last = if fields[1].ends_with(", First>") {
            let next = lines.next().unwrap();
            usize::from_str_radix(next.split(';').next().unwrap(), 16).unwrap()
        } else {
            first
        };
        categories[first..=last].fill(fields[2]);
    }

    let mut ranges: BTreeMap<&str, Vec<(usize, usize)>> = BTreeMap::new();
    for (cp, &category) in categories.iter().enumerate() {
        if category == "Cs" {
            continue;
        }
        for name in [category, &category[..1]] {
            let spans = ranges.entry(name).or_default();
            match spans.last_mut() {
                Some(span) if span.1 + 1 == cp => span.1 = cp,
                _ => spans.push((cp, cp)),
            }
        }
    }

    let mut rs = format!(
        "//! Unicode general category tables, Unicode {version}.\n\
         //! Generated by examples/gen_unicode_categories.rs; do not edit by hand.\n\n\
         /// The code point ranges of a general category such as `L` or `Lu`.\n\
         pub fn category_ranges(name: &str) -> Option<&'static [(char, char)]> {{\n    \
         Some(match name {{\n"
    );
    for name in ranges.keys() {
        writeln!(rs, "        \"{name}\" => {},", name.to_uppercase()).unwrap();
    }
    rs += "        _ => return None,\n    })\n}\n";
    for (name, spans) in &ranges {
        write!(
            rs,
            "\n#[rustfmt::skip]\nstatic {}: &[(char, char)] = &[\n",
            name.to_uppercase()
        )
        .unwrap();
        for row in spans.chunks(4) {
            let row: Vec<String> = row
                .iter()
                .map(|(lo, hi)| format!("('\\u{{{lo:x}}}', '\\u{{{hi:x}}}')"))
                .collect();
            writeln!(rs, "    {},", row.join(", ")).unwrap();
        }
        rs += "];\n";
    }
    std::fs::write(out, rs).unwrap();
}
